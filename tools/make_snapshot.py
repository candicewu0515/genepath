"""Fetch a small offline snapshot of recruiting trials from ClinicalTrials.gov API v2.

Usage: python3 tools/make_snapshot.py
Writes data/trials-snapshot.json and snapshot.js (same data, loadable from file://).
"""
import datetime, json, math, pathlib, re, urllib.parse, urllib.request

ROOT = pathlib.Path(__file__).resolve().parent.parent
ORIGIN = {"label": "Iowa City, IA", "lat": 41.6611, "lon": -91.5302}
RADIUS_MI = 150
CONDITIONS = {
    "afib": "atrial fibrillation",
    "chol": "hypercholesterolemia",
    "gerd": "gastroesophageal reflux",
    "depression": "depression",
    "oa": "osteoarthritis",
    "ra": "rheumatoid arthritis",
    "crc": "colorectal cancer",
    "alzheimers": "Alzheimer disease",
    "t2d": "type 2 diabetes",
}
FIELDS = ",".join([
    "NCTId", "BriefTitle", "OverallStatus", "BriefSummary", "EligibilityCriteria",
    "MinimumAge", "MaximumAge", "Sex", "Phase", "StudyType",
    "CentralContactName", "CentralContactPhone", "CentralContactEMail",
    "LocationFacility", "LocationCity", "LocationState", "LocationCountry",
    "LocationGeoPoint", "LocationStatus",
])


def stamp_index(filename):
    """Add a build date to the <script src> so browsers pick up a new data file."""
    idx = ROOT / "index.html"
    html = idx.read_text()
    new = re.sub(r'(<script src="%s)(\?v=[^"]*)?(")' % re.escape(filename),
                 lambda m: m.group(1) + "?v=" + datetime.date.today().isoformat() + m.group(3), html)
    if new != html:
        idx.write_text(new)

def miles(a_lat, a_lon, b_lat, b_lon):
    r = 3958.8
    p1, p2 = math.radians(a_lat), math.radians(b_lat)
    dp, dl = p2 - p1, math.radians(b_lon - a_lon)
    h = math.sin(dp / 2) ** 2 + math.cos(p1) * math.cos(p2) * math.sin(dl / 2) ** 2
    return 2 * r * math.asin(math.sqrt(h))


def fetch_at(term, radius):
    params = {"query.cond": term, "filter.overallStatus": "RECRUITING", "pageSize": 6, "fields": FIELDS}
    if radius:
        params["filter.geo"] = f"distance({ORIGIN['lat']},{ORIGIN['lon']},{radius}mi)"
    q = urllib.parse.urlencode(params)
    with urllib.request.urlopen("https://clinicaltrials.gov/api/v2/studies?" + q, timeout=40) as r:
        return json.load(r)["studies"]


def fetch(term):
    """Widen the search until the saved sample has something to show."""
    for radius in (RADIUS_MI, 500, None):
        studies = fetch_at(term, radius)
        if len(studies) >= 4 or radius is None:
            return studies, radius
    return studies, None


def trim(study):
    mod = study["protocolSection"].get("contactsLocationsModule", {})
    locs = [l for l in mod.get("locations", []) if l.get("geoPoint")]
    locs.sort(key=lambda l: miles(ORIGIN["lat"], ORIGIN["lon"], l["geoPoint"]["lat"], l["geoPoint"]["lon"]))
    mod["locations"] = locs[:5]
    return study


snap = {
    "fetchedAt": datetime.date.today().isoformat(),
    "source": "ClinicalTrials.gov API v2 (https://clinicaltrials.gov/api/v2/studies)",
    "origin": ORIGIN,
    "radiusMiles": RADIUS_MI,
    "conditions": {},
    "radiusByCondition": {},
}
for key, term in CONDITIONS.items():
    studies, radius = fetch(term)
    snap["conditions"][key] = [trim(s) for s in studies]
    snap["radiusByCondition"][key] = radius
text = json.dumps(snap, ensure_ascii=False, indent=1)
(ROOT / "data" / "trials-snapshot.json").write_text(text)
(ROOT / "snapshot.js").write_text("// Auto-generated by tools/make_snapshot.py. Do not edit by hand.\nwindow.TRIAL_SNAPSHOT = " + text + ";\n")
stamp_index("snapshot.js")
print("ok", {k: (len(v), snap["radiusByCondition"][k]) for k, v in snap["conditions"].items()})
